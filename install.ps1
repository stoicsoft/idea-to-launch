# Software Builder installer for Windows (PowerShell 5.1 or newer).
#
#   irm https://raw.githubusercontent.com/OWNER/REPO/main/install.ps1 | iex
#
# To choose tools, download the script and run it with options:
#   .\install.ps1 -Agent claude,cursor     .\install.ps1 -All     .\install.ps1 -Uninstall
# Copies the skills into every AI tool it finds. Uses Node.js when available
# (same logic as npx), and plain PowerShell otherwise. No admin rights needed.
param(
  [string[]]$Agent = @(),
  [switch]$All,
  [switch]$Uninstall,
  [switch]$DryRun,
  [string]$Ref = 'main'
)
$ErrorActionPreference = 'Stop'

$Repo = if ($env:SOFTWARE_BUILDER_REPO) { $env:SOFTWARE_BUILDER_REPO } else { 'OWNER/REPO' }
$Skills = @('app-builder', 'app-idea', 'app-plan', 'app-design', 'app-build', 'app-change', 'app-fix', 'app-review', 'app-launch')
$Suite = 'software-builder'
$Agent = @($Agent | ForEach-Object { $_ -split ',' } | Where-Object { $_ })

$Agents = @(
# BEGIN AGENTS (generated by scripts/build.mjs)
  @{ Id = 'claude'; Name = 'Claude Code (and the Code tab in Claude Desktop)'; Home = '.claude/skills'; Detect = @('.claude'); Covers = @() }
  @{ Id = 'codex'; Name = 'Codex (CLI, IDE extension and Codex app)'; Home = '.codex/skills'; Detect = @('.codex'); Covers = @() }
  @{ Id = 'gemini'; Name = 'Gemini CLI'; Home = '.gemini/skills'; Detect = @('.gemini'); Covers = @() }
  @{ Id = 'copilot'; Name = 'GitHub Copilot (CLI and VS Code)'; Home = '.copilot/skills'; Detect = @('.copilot'); Covers = @() }
  @{ Id = 'opencode'; Name = 'OpenCode'; Home = '.config/opencode/skills'; Detect = @('.config/opencode'); Covers = @() }
  @{ Id = 'windsurf'; Name = 'Windsurf'; Home = '.codeium/windsurf/skills'; Detect = @('.codeium/windsurf'); Covers = @() }
  @{ Id = 'cline'; Name = 'Cline'; Home = '.agents/skills'; Detect = @('.cline'); Covers = @() }
  @{ Id = 'kiro'; Name = 'Kiro'; Home = '.kiro/skills'; Detect = @('.kiro'); Covers = @() }
  @{ Id = 'qwen'; Name = 'Qwen Code'; Home = '.qwen/skills'; Detect = @('.qwen'); Covers = @() }
  @{ Id = 'roo'; Name = 'Roo Code'; Home = '.roo/skills'; Detect = @('.roo'); Covers = @() }
  @{ Id = 'kilo'; Name = 'Kilo Code'; Home = '.kilo/skills'; Detect = @('.kilo'); Covers = @() }
  @{ Id = 'droid'; Name = 'Factory Droid'; Home = '.factory/skills'; Detect = @('.factory'); Covers = @() }
  @{ Id = 'goose'; Name = 'Goose'; Home = '.config/goose/skills'; Detect = @('.config/goose'); Covers = @() }
  @{ Id = 'amp'; Name = 'Amp'; Home = '.config/agents/skills'; Detect = @('.config/amp'); Covers = @() }
  @{ Id = 'antigravity'; Name = 'Antigravity'; Home = '.gemini/antigravity/skills'; Detect = @('.gemini/antigravity'); Covers = @() }
  @{ Id = 'trae'; Name = 'Trae'; Home = '.trae/skills'; Detect = @('.trae'); Covers = @() }
  @{ Id = 'continue'; Name = 'Continue'; Home = '.continue/skills'; Detect = @('.continue'); Covers = @() }
  @{ Id = 'augment'; Name = 'Augment'; Home = '.augment/skills'; Detect = @('.augment'); Covers = @() }
  @{ Id = 'junie'; Name = 'Junie'; Home = '.junie/skills'; Detect = @('.junie'); Covers = @() }
  @{ Id = 'cursor'; Name = 'Cursor'; Home = '.cursor/skills'; Detect = @('.cursor'); Covers = @('.claude/skills', '.codex/skills', '.agents/skills') }
# END AGENTS
)

$UserHome = [Environment]::GetFolderPath('UserProfile')
function Resolve-HomePath([string]$Rel) {
  if ($Rel -eq '.claude/skills' -and $env:CLAUDE_CONFIG_DIR) { return Join-Path $env:CLAUDE_CONFIG_DIR 'skills' }
  if ($Rel -eq '.codex/skills' -and $env:CODEX_HOME) { return Join-Path $env:CODEX_HOME 'skills' }
  return Join-Path $UserHome ($Rel -replace '/', '\')
}
function Test-Ours([string]$Dir) {
  $file = Join-Path $Dir 'SKILL.md'
  return (Test-Path $file) -and ((Get-Content -Raw $file) -match "suite:\s*[`"']?$Suite")
}

# ── Find the skills: this checkout, or a fresh download ──────────────────────
$Src = $null
if ($PSScriptRoot -and (Test-Path (Join-Path $PSScriptRoot 'skills/app-builder/SKILL.md'))) {
  $Src = $PSScriptRoot
} else {
  if ($Repo -like 'OWNER/*') { throw 'This copy of the installer has no repository set. Run it from a checkout, or set $env:SOFTWARE_BUILDER_REPO = "owner/repo".' }
  $Tmp = Join-Path ([IO.Path]::GetTempPath()) ("software-builder-" + [Guid]::NewGuid())
  New-Item -ItemType Directory -Path $Tmp | Out-Null
  Write-Host "Downloading Software Builder ($Repo@$Ref)..."
  $Zip = Join-Path $Tmp 'src.zip'
  [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
  Invoke-WebRequest -UseBasicParsing -Uri "https://codeload.github.com/$Repo/zip/$Ref" -OutFile $Zip
  Expand-Archive -Path $Zip -DestinationPath $Tmp
  $Src = (Get-ChildItem -Directory $Tmp | Select-Object -First 1).FullName
  if (-not (Test-Path (Join-Path $Src 'skills/app-builder/SKILL.md'))) { throw 'The download did not contain the skills.' }
}

# ── Prefer the Node installer: same behaviour as npx ─────────────────────────
$Node = Get-Command node -ErrorAction SilentlyContinue
if ($Node -and ([int]((& node -p 'process.versions.node').Split('.')[0]) -ge 18)) {
  $NodeArgs = @((Join-Path $Src 'scripts/cli.mjs'), $(if ($Uninstall) { 'uninstall' } else { 'install' }))
  if ($Agent.Count) { $NodeArgs += @('--agent', ($Agent -join ',')) }
  if ($All) { $NodeArgs += '--all' }
  if ($DryRun) { $NodeArgs += '--dry-run' }
  & node @NodeArgs
  exit $LASTEXITCODE
}

# ── Plain-PowerShell fallback ────────────────────────────────────────────────
$Selected = $Agents | Where-Object {
  if ($Agent.Count) { $Agent -contains $_.Id }
  elseif ($All) { $true }
  else { @($_.Detect | Where-Object { Test-Path (Join-Path $UserHome ($_ -replace '/', '\')) }).Count -gt 0 }
}
if (-not $Selected) {
  Write-Host 'No AI tools found on this computer. Choose one with -Agent (for example: -Agent claude) or use -All.'
  exit 1
}

$Targets = @()
foreach ($a in $Selected) {
  $dir = Resolve-HomePath $a.Home
  if ($Uninstall) {
    foreach ($s in $Skills) {
      $dest = Join-Path $dir $s
      if (Test-Ours $dest) { Write-Host "  removed $dest"; if (-not $DryRun) { Remove-Item -Recurse -Force $dest } }
    }
    continue
  }
  $shared = $a.Covers | ForEach-Object { Resolve-HomePath $_ } | Where-Object { $Targets -contains $_ } | Select-Object -First 1
  if ($Targets -contains $dir) { $shared = $dir }
  if ($shared) { Write-Host "  + $($a.Name)`n      uses the copy in $shared"; continue }
  $Targets += $dir
  foreach ($s in $Skills) {
    $dest = Join-Path $dir $s
    if ((Test-Path $dest) -and -not (Test-Ours $dest)) { Write-Host "  ! Skipped ${dest}: a different skill with this name is already there"; continue }
    if (-not $DryRun) {
      New-Item -ItemType Directory -Force -Path $dir | Out-Null
      if (Test-Path $dest) { Remove-Item -Recurse -Force $dest }
      Copy-Item -Recurse (Join-Path $Src "skills/$s") $dest
    }
  }
  Write-Host "  + $($a.Name)`n      $dir"
}
if (-not $Uninstall -and -not $DryRun) {
  Write-Host ''
  Write-Host 'Done. Restart your AI tool (or start a new chat), then say something like:'
  Write-Host '  "I want to build an app for my business. Can you help?"'
}
