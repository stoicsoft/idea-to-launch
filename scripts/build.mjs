#!/usr/bin/env node
// Keeps generated copies in sync with their single source:
//   shared/*.md                → skills/<every skill>/references/
//   shared/essentials.md       → the top of every skills/<skill>/SKILL.md
//   skills/app-design/references/directions.md → skills/app-build/references/
//   scripts/agents.mjs         → install.sh, install.ps1, docs/install.md
//
// Every skill must work when installed on its own (for example a single zip
// uploaded to Claude Desktop), so shared guidance is copied, not linked.
//
//   node scripts/build.mjs           write the copies
//   node scripts/build.mjs --check   exit 1 if anything is out of date
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { AGENTS, SKILLS } from './agents.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')
const stale = []

const GENERATED_NOTE = (source) => `<!-- Generated from ${source} by scripts/build.mjs. Edit the source, then run npm run build. -->\n\n`

function write(file, content) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null
  if (current === content) return
  if (check) {
    stale.push(file.slice(ROOT.length + 1))
    return
  }
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, content)
}

function replaceBlock(file, begin, end, body) {
  const text = readFileSync(file, 'utf8')
  const start = text.indexOf(begin)
  const stop = text.indexOf(end)
  if (start < 0 || stop < start) throw new Error(`${file}: markers "${begin}" … "${end}" not found`)
  write(file, text.slice(0, start + begin.length) + '\n' + body + text.slice(stop))
}

// 1. Shared references into every skill.
const ESSENTIALS = 'essentials.md'
const shared = readdirSync(join(ROOT, 'shared')).filter((f) => f.endsWith('.md') && f !== ESSENTIALS)
for (const skill of SKILLS) {
  for (const file of shared) {
    const source = readFileSync(join(ROOT, 'shared', file), 'utf8')
    write(join(ROOT, 'skills', skill, 'references', file), GENERATED_NOTE(`shared/${file}`) + source)
  }
}

// 2. Per-skill extras.
const EXTRAS = [['skills/app-design/references/directions.md', 'skills/app-build/references/directions.md']]
for (const [from, to] of EXTRAS) {
  write(join(ROOT, to), GENERATED_NOTE(from) + readFileSync(join(ROOT, from), 'utf8'))
}

// 3. The essentials, inline in every SKILL.md. Hosts don't always let the
//    assistant open reference files (Claude Code asks before reading outside
//    the project), and these rules must hold even then.
const essentials = readFileSync(join(ROOT, 'shared', ESSENTIALS), 'utf8')
for (const skill of SKILLS) {
  replaceBlock(join(ROOT, 'skills', skill, 'SKILL.md'), '<!-- BEGIN ESSENTIALS (generated from shared/essentials.md by scripts/build.mjs) -->', '<!-- END ESSENTIALS -->', essentials)
}

// 4. The tool table, into both installers and the install guide.
const rel = (p) => p.replace(/^~\//, '')
const shTable = AGENTS.map((a) => `${a.id}|${a.name}|${rel(a.home)}|${a.detect.map(rel).join(' ')}|${(a.covers ?? []).map(rel).join(' ')}`).join('\n')
replaceBlock(join(ROOT, 'install.sh'), "AGENTS_TABLE='# BEGIN AGENTS (generated by scripts/build.mjs)", "# END AGENTS'", shTable + '\n')

const psRows = AGENTS.map(
  (a) => `  @{ Id = '${a.id}'; Name = '${a.name.replace(/'/g, "''")}'; Home = '${rel(a.home)}'; Detect = @(${a.detect.map((d) => `'${rel(d)}'`).join(', ')}); Covers = @(${(a.covers ?? []).map((c) => `'${rel(c)}'`).join(', ')}) }`,
).join('\n')
replaceBlock(join(ROOT, 'install.ps1'), '# BEGIN AGENTS (generated by scripts/build.mjs)', '# END AGENTS', psRows + '\n')

const mdRows = AGENTS.map((a) => `| ${a.name} | \`${a.id}\` | \`${a.home}\` | \`${a.project}\` |`).join('\n')
replaceBlock(
  join(ROOT, 'docs', 'install.md'),
  '<!-- BEGIN AGENTS (generated by scripts/build.mjs) -->',
  '<!-- END AGENTS -->',
  `| Tool | \`--agent\` | Your user folder | Inside a project (\`--project\`) |\n|---|---|---|---|\n${mdRows}\n`,
)

if (check) {
  if (stale.length) {
    console.error(`Out of date (run "npm run build"):\n  ${stale.join('\n  ')}`)
    process.exit(1)
  }
  console.log('build: everything is in sync')
} else {
  console.log(`build: synced ${shared.length} shared references and the essentials into ${SKILLS.length} skills, ${EXTRAS.length} extra(s), and the tool table`)
}
