#!/usr/bin/env bash
# Idea to Launch installer for macOS and Linux.
#
#   curl -fsSL https://raw.githubusercontent.com/OWNER/idea-to-launch/main/install.sh | bash
#   curl -fsSL https://raw.githubusercontent.com/OWNER/idea-to-launch/main/install.sh | bash -s -- --agent claude,cursor
#
# Options: --agent <ids>  --all  --project [dir]  --uninstall  --dry-run  --ref <branch-or-tag>
# Copies the skills into every AI tool it finds. Uses Node.js when available
# (same logic as `npx`), and plain shell otherwise. It never needs sudo.
set -euo pipefail

REPO="${IDEA_TO_LAUNCH_REPO:-OWNER/idea-to-launch}"
REF="main"
SKILLS="app-builder app-idea app-plan app-design app-build app-change app-fix app-review app-launch"
SUITE="idea-to-launch"

AGENTS_TABLE='# BEGIN AGENTS (generated by scripts/build.mjs)
claude|Claude Code (and the Code tab in Claude Desktop)|.claude/skills|.claude|
codex|Codex (CLI, IDE extension and Codex app)|.codex/skills|.codex|
gemini|Gemini CLI|.gemini/skills|.gemini|
copilot|GitHub Copilot (CLI and VS Code)|.copilot/skills|.copilot|
opencode|OpenCode|.config/opencode/skills|.config/opencode|
windsurf|Windsurf|.codeium/windsurf/skills|.codeium/windsurf|
cline|Cline|.agents/skills|.cline|
kiro|Kiro|.kiro/skills|.kiro|
qwen|Qwen Code|.qwen/skills|.qwen|
roo|Roo Code|.roo/skills|.roo|
kilo|Kilo Code|.kilo/skills|.kilo|
droid|Factory Droid|.factory/skills|.factory|
goose|Goose|.config/goose/skills|.config/goose|
amp|Amp|.config/agents/skills|.config/amp|
antigravity|Antigravity|.gemini/antigravity/skills|.gemini/antigravity|
trae|Trae|.trae/skills|.trae|
continue|Continue|.continue/skills|.continue|
augment|Augment|.augment/skills|.augment|
junie|Junie|.junie/skills|.junie|
cursor|Cursor|.cursor/skills|.cursor|.claude/skills .codex/skills .agents/skills
# END AGENTS'

say() { printf '%s\n' "$*"; }
die() { printf 'idea-to-launch: %s\n' "$*" >&2; exit 1; }

# ── Arguments ────────────────────────────────────────────────────────────────
ARGS=()
MODE="install"
ONLY=""
ALL=0
DRY=0
PROJECT=""
while [ $# -gt 0 ]; do
  case "$1" in
    --ref) REF="${2:?--ref needs a value}"; shift 2 ;;
    --uninstall) MODE="uninstall"; shift ;;
    --agent|--agents) ONLY="${2:?--agent needs a value}"; ARGS+=("--agent" "$2"); shift 2 ;;
    --all) ALL=1; ARGS+=("--all"); shift ;;
    --dry-run) DRY=1; ARGS+=("--dry-run"); shift ;;
    --project)
      if [ $# -gt 1 ] && [ "${2#-}" = "$2" ]; then PROJECT="$2"; shift 2; else PROJECT="$PWD"; shift; fi
      ARGS+=("--project" "$PROJECT") ;;
    --force) ARGS+=("--force"); shift ;;
    -h|--help) sed -n '2,10p' "$0" 2>/dev/null || true; exit 0 ;;
    *) die "unknown option: $1" ;;
  esac
done

# ── Find the skills: this checkout, or a fresh download ──────────────────────
SRC=""
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd || true)"
if [ -n "$SCRIPT_DIR" ] && [ -f "$SCRIPT_DIR/skills/app-builder/SKILL.md" ]; then
  SRC="$SCRIPT_DIR"
else
  case "$REPO" in OWNER/*) die "this copy of the installer has no repository set; run it from a checkout, or set IDEA_TO_LAUNCH_REPO=owner/repo" ;; esac
  command -v curl >/dev/null 2>&1 || die "curl is needed to download the skills"
  command -v tar >/dev/null 2>&1 || die "tar is needed to unpack the skills"
  TMP="$(mktemp -d)"
  trap 'rm -rf "$TMP"' EXIT
  say "Downloading Idea to Launch ($REPO@$REF)…"
  curl -fsSL "https://codeload.github.com/$REPO/tar.gz/$REF" | tar -xz -C "$TMP" || die "download failed; check your internet connection"
  SRC="$(find "$TMP" -mindepth 1 -maxdepth 1 -type d | head -n 1)"
  [ -f "$SRC/skills/app-builder/SKILL.md" ] || die "the download did not contain the skills"
fi

# ── Prefer the Node installer: same behaviour as npx ─────────────────────────
if [ -z "${IDEA_TO_LAUNCH_NO_NODE:-}" ] && command -v node >/dev/null 2>&1 && node -e 'process.exit(+process.versions.node.split(".")[0] >= 18 ? 0 : 1)' 2>/dev/null; then
  if [ "$MODE" = "uninstall" ]; then exec node "$SRC/scripts/cli.mjs" uninstall ${ARGS[@]+"${ARGS[@]}"}; fi
  exec node "$SRC/scripts/cli.mjs" install ${ARGS[@]+"${ARGS[@]}"}
fi

# ── Plain-shell fallback ─────────────────────────────────────────────────────
home_path() { # relative path under $HOME, honouring CLAUDE_CONFIG_DIR / CODEX_HOME
  case "$1" in
    .claude/skills) printf '%s' "${CLAUDE_CONFIG_DIR:-$HOME/.claude}/skills" ;;
    .codex/skills) printf '%s' "${CODEX_HOME:-$HOME/.codex}/skills" ;;
    *) printf '%s' "$HOME/$1" ;;
  esac
}
is_ours() { [ -f "$1/SKILL.md" ] && grep -Eq "suite:[[:space:]]*[\"']?$SUITE" "$1/SKILL.md"; }
wanted() { # is this agent selected?
  local id="$1" detect="$2"
  if [ -n "$ONLY" ]; then case ",$ONLY," in *",$id,"*) return 0 ;; *) return 1 ;; esac; fi
  [ "$ALL" = 1 ] && return 0
  for d in $detect; do [ -e "$HOME/$d" ] && return 0; done
  return 1
}

[ -z "$PROJECT" ] || die "--project needs Node.js 18 or newer; install Node.js (nodejs.org) or install for your user instead"

TARGETS=""
COUNT=0
while IFS='|' read -r id name home detect covers; do
  case "$id" in ''|\#*) continue ;; esac
  wanted "$id" "$detect" || continue
  COUNT=$((COUNT + 1))
  dir="$(home_path "$home")"
  if [ "$MODE" = "uninstall" ]; then
    for s in $SKILLS; do
      if is_ours "$dir/$s"; then
        say "  removed ${dir/#$HOME/~}/$s"
        [ "$DRY" = 1 ] || rm -rf "${dir:?}/$s"
      fi
    done
    continue
  fi
  shared=""
  for c in $covers; do
    case " $TARGETS " in *" $(home_path "$c") "*) shared="$(home_path "$c")" ;; esac
  done
  case " $TARGETS " in *" $dir "*) shared="$dir" ;; esac
  if [ -n "$shared" ]; then
    say "  ✓ $name"; say "      uses the copy in ${shared/#$HOME/~}"
    continue
  fi
  TARGETS="$TARGETS $dir"
  for s in $SKILLS; do
    if [ -e "$dir/$s" ] && ! is_ours "$dir/$s"; then
      say "  ! Skipped ${dir/#$HOME/~}/$s: a different skill with this name is already there"
      continue
    fi
    if [ "$DRY" = 0 ]; then
      mkdir -p "$dir"
      rm -rf "${dir:?}/$s"
      cp -R "$SRC/skills/$s" "$dir/$s"
    fi
  done
  say "  ✓ $name"; say "      ${dir/#$HOME/~}"
done <<EOF
$AGENTS_TABLE
EOF

if [ "$COUNT" = 0 ]; then
  say "No AI tools found on this computer. Choose one with --agent (for example: --agent claude) or use --all."
  exit 1
fi
if [ "$MODE" = "install" ] && [ "$DRY" = 0 ]; then
  say ""
  say "Done. Restart your AI tool (or start a new chat), then say something like:"
  say '  "I want to build an app for my business. Can you help?"'
fi
